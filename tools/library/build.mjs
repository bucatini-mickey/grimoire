// Writes src/core/scripts/library.ts: the scripts the script page offers, from the botcscripts.com
// download (top.json, made by fetch.mjs) and our own words about each (blurbs.txt).
//   node tools/library/fetch.mjs tools/library   refresh top.json (most favourited first)
//   node tools/library/build.mjs                 write library.ts
// blurbs.txt: one line a script, `slug|level|about`, level B(eginner), I(ntermediate), A(dvanced).
// A script is in the library only if it has a line there, so new ones in top.json wait for words.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATALOG } from '../../src/core/script.ts';
import { TRAVELLERS } from '../../src/core/scripts/travellers.ts';
import { EXPERIMENTAL, LORIC } from '../../src/core/scripts/experimental.ts';
import { FABLED } from '../../src/core/scripts/fabled.ts';

const here = dirname(fileURLToPath(import.meta.url));
const top = JSON.parse(readFileSync(join(here, 'top.json'), 'utf8'));
const blurbs = new Map(readFileSync(join(here, 'blurbs.txt'), 'utf8').split('\n').filter(Boolean).map((l) => {
	const [slug, level, ...about] = l.split('|');
	return [slug, { level: { B: 'beginner', I: 'intermediate', A: 'advanced' }[level], about: about.join('|').trim() }];
}));

// botcscripts ids are ours without the hyphens (fortuneteller, lilmonsta).
const key = (id) => id.toLowerCase().replace(/[^a-z]/g, '');
const kinds = new Map();
for (const c of CATALOG) kinds.set(key(c.id), [c.id, 'char']);
for (const c of [...Object.values(TRAVELLERS).flat(), ...EXPERIMENTAL.filter((x) => x.team === 'traveller')]) kinds.set(key(c.id), [c.id, 'traveller']);
for (const f of FABLED) kinds.set(key(f.id), [f.id, 'fabled']);
for (const l of LORIC) kinds.set(key(l.id), [l.id, 'loric']);

// The Pandemonium Institute's own small scripts, and the No Rolls Barred one it made.
const TPI = ['Laissez un Faire', 'No Greater Joy', 'Race to the Bottom', "Frankenstein's Mayor", 'Miserable Little Pile of Secrets', 'Comrade Demon', 'Late Night Drive By', 'A Lleech of Distrust', 'Over the River', 'A Different Kind of Mathematics'];
const EDITIONS = { 'Trouble Brewing': 'trouble-brewing', 'Bad Moon Rising': 'bad-moon-rising', 'Sects and Violets': 'sects-and-violets' };
const unhtml = (t) => t.replace(/&amp;/g, '&').replace(/&#x27;/g, "'").replace(/&quot;/g, '"');
const clean = (t) => unhtml(t).replace(/ \([\d.]+\)$/, '').trim();

const out = [];
for (const r of top) {
	const name = clean(r.title);
	const slug = name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
	const words = blurbs.get(slug);
	if (!words || !Array.isArray(r.content)) continue;
	const meta = r.content.find((c) => c.id === '_meta') ?? {};
	const e = { id: EDITIONS[name] ?? (slug === 'laissez-un-faire' ? 'laissez-un-faire' : 'lib:' + slug), name, author: clean(r.author || meta.author || '') .replace(/^—$/, ''),
		kind: EDITIONS[name] ? 'edition' : TPI.includes(name) || /Carousel Collection/.test(r.tags) ? 'official' : 'popular',
		size: r.type === 'Teensyville' ? 'teensy' : 'full', level: words.level, favs: r.favs, chars: [], travellers: [], fabled: [], loric: [], rules: [], about: words.about,
		url: `https://www.botcscripts.com/script/${r.id}/${r.ver}` };
	for (const c of r.content) {
		if (c.id === '_meta') continue;
		const k = kinds.get(key(typeof c === 'string' ? c : c.id));
		if (!k) throw new Error(`${name}: unknown character ${c.id ?? c}`);
		({ char: e.chars, traveller: e.travellers, fabled: e.fabled, loric: e.loric })[k[1]].push(k[0]);
	}
	e.rules = [].concat(meta.bootlegger ?? []).map((x) => String(x).trim()).filter(Boolean);
	out.push(e);
}
const missing = [...blurbs.keys()].filter((s) => !out.some((e) => e.id.endsWith(s)));
if (missing.length) throw new Error('blurbs with no script: ' + missing.join(', '));

const q = (s) => JSON.stringify(s);
const list = (a) => q(a.join(' '));
const lines = out.map((e) => `\t{ id: ${q(e.id)}, name: ${q(e.name)}, author: ${q(e.author)}, kind: '${e.kind}', size: '${e.size}', level: '${e.level}', favs: ${e.favs},\n\t\tchars: ${list(e.chars)}${e.travellers.length ? `,\n\t\ttravellers: ${list(e.travellers)}` : ''}${e.fabled.length ? `, fabled: ${list(e.fabled)}` : ''}${e.loric.length ? `, loric: ${list(e.loric)}` : ''}${e.rules.length ? `,\n\t\trules: ${q(e.rules)}` : ''},\n\t\tabout: ${q(e.about)},\n\t\turl: ${q(e.url)} }`);
writeFileSync(join(here, '../../src/core/scripts/library.ts'), `/**
 * library.ts - the scripts the script page offers: the three editions, the Pandemonium
 * Institute's own small scripts and its Carousel Collection, and the community's most
 * favourited on botcscripts.com (November 2026). Who made each is kept with it; the words
 * about each are ours.
 * GENERATED by tools/library/build.mjs from tools/library/top.json and blurbs.txt: edit those.
 * Character lists are ids separated by spaces, in the script's own order.
 */
export interface LibraryEntry {
	/** The script id the engine plays: an edition's own, or 'lib:<slug>'. */
	id: string;
	name: string;
	author: string;
	/** An edition, another official script (TPI's Teensyville and Carousel Collection), or a popular community one. */
	kind: 'edition' | 'official' | 'popular';
	/** A full script, or a Teensyville one made for five or six players. */
	size: 'full' | 'teensy';
	level: 'beginner' | 'intermediate' | 'advanced';
	/** Favourites on botcscripts.com when it was fetched. */
	favs: number;
	chars: string;
	travellers?: string;
	fabled?: string;
	loric?: string;
	/** The author's house rules (the Bootlegger's), in their words. */
	rules?: string[];
	about: string;
	url: string;
}

export const LIBRARY: LibraryEntry[] = [
${lines.join(',\n')}
];
`);
console.log(`library.ts: ${out.length} scripts (${out.filter((e) => e.kind === 'official').length} official, ${out.filter((e) => e.kind === 'popular').length} popular)`);
